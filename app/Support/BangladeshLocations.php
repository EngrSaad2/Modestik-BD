        $suburbanThanas = [
            'savar', 'safor', 'সাভার',
            'keraniganj', 'keranigonj', 'কেরাণীগঞ্জ', 'কেরানীগঞ্জ',
            'dhamrai', 'ধামরাই',
            'dohar', 'দোহার',
            'nawabganj', 'nawabgonj', 'নবাবগঞ্জ'
        ];
        $isThanaSuburban = in_array($thana, $suburbanThanas);

        if ($isDistrictDhaka) {
            if ($isThanaSuburban) {
                // Suburban Areas / Dhaka Sub Urban (ID 3 / Matches 'sub')
                return \App\Models\ShippingZone::active()
                    ->where(function($query) {
                        $query->where('name', 'like', '%sub%')
                              ->orWhere('id', 3);
                    })->first() ?? \App\Models\ShippingZone::active()->first();
            } else {
                // Inside Dhaka City / Inside Dhaka (ID 1 / Matches 'inside')
                return \App\Models\ShippingZone::active()
                    ->where(function($query) {
                        $query->where('name', 'like', '%inside%')
                              ->orWhere('id', 1);
                    })->first() ?? \App\Models\ShippingZone::active()->first();
            }
        } else {
            // Outside Dhaka City / Outside Dhaka (ID 2 / Matches 'outside')
            return \App\Models\ShippingZone::active()
                ->where(function($query) {
                    $query->where('name', 'like', '%outside%')
                          ->orWhere('id', 2);
                })->first() ?? \App\Models\ShippingZone::active()->first();
        }
    }
